// var, let and const

var name = "Hasan";
let age = 22;
const university = "Daffodil International University";

console.log(name);
console.log(age);
console.log(university);

// Changing let variable

let city = "Dhaka";

console.log(city);

city = "Savar";

console.log(city);

// Data Types

let studentName = "Hasan";       // String
let studentAge = 22;             // Number
let passed = true;               // Boolean
let result;                      // Undefined
let value = null;                // Null
let skills = ["JavaScript", "Python", "React"]; // Array

console.log(typeof studentName);
console.log(typeof studentAge);
console.log(typeof passed);
console.log(typeof result);
console.log(typeof value);
console.log(typeof skills);

